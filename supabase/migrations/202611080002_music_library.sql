begin;

create table public.playlists (
  id bigint generated by default as identity primary key,
  name text not null,
  description text not null default '',
  cover text not null default '♡',
  created_at timestamptz not null default now()
);

create table public.songs (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 200),
  artist text not null default 'Nghệ sĩ chưa rõ' check (char_length(artist) <= 200),
  album text not null default 'Đĩa đơn' check (char_length(album) <= 200),
  duration text not null default '--:--',
  audio_url text,
  cover text not null default '♫',
  is_active boolean not null default true,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

alter table public.playlists enable row level security;
alter table public.songs enable row level security;
-- The public read policy checks this helper only for inactive rows; it returns
-- false for anonymous users because auth.uid() is null.
grant execute on function public.is_admin() to anon;

create policy "Playlists are readable by everyone" on public.playlists
  for select to anon, authenticated using (true);
create policy "Songs are readable by everyone" on public.songs
  for select to anon, authenticated using (is_active or (select public.is_admin()));
create policy "Admins manage playlists" on public.playlists
  for all to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));
create policy "Admins manage songs" on public.songs
  for all to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));
grant select on public.playlists, public.songs to anon, authenticated;
grant insert, update, delete on public.playlists, public.songs to authenticated;
grant usage, select on all sequences in schema public to authenticated;

insert into public.playlists(name, description, cover)
