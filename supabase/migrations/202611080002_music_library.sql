  ('Mưa đông không lạnh', 'Akira Phan', 'Giai điệu thanh xuân', '04:01', '🌧️');

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('music', 'music', true, 31457280, array['audio/mpeg','audio/mp3','audio/wav','audio/x-wav','audio/ogg','audio/mp4','audio/aac','audio/x-m4a','application/octet-stream'])
on conflict (id) do update set public = excluded.public, file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;

create policy "Music files are public to read" on storage.objects
  for select to anon, authenticated using (bucket_id = 'music');
create policy "Admins upload music files" on storage.objects
  for insert to authenticated with check (bucket_id = 'music' and (select public.is_admin()));
create policy "Admins update music files" on storage.objects
  for update to authenticated using (bucket_id = 'music' and (select public.is_admin()))
  with check (bucket_id = 'music' and (select public.is_admin()));
create policy "Admins delete music files" on storage.objects
  for delete to authenticated using (bucket_id = 'music' and (select public.is_admin()));

commit;
